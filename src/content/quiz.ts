export function questionsFor(
  id: string,
  title: string,
  goal: string,
): Question[] {
  const r = rows[id];
  if (!r) throw new Error(`Нет вопросов: ${id}`);
  const list = [0, 5].map((offset, i) => ({
    id: `${id}-q${i + 1}`,
    prompt: r[offset],
    options: r.slice(offset + 1, offset + 4),
    correct: 0,
    explanation: r[offset + 4],
    topic: title,
  }));
  list.push({
    id: `${id}-q3`,
    prompt: "Как построить обоснованный ответ по методу СТЭК?",
    options: [
      "Ситуация → диапазоны/правила → расчёт → действие с оговорками",
      "Результат раздачи → оправдание действия",
      "Выбрать действие без вводных",
    ],
    correct: 0,
    explanation: `Цель занятия: ${goal} Назовите условия и допущения; выигрыш одной раздачи не заменяет аргументацию.`,
    topic: title,
  });
  // Детерминированная перестановка, чтобы правильный ответ не стоял всегда первым.
  return list.map((q, i) => {
    const shift = (Number(id.slice(-2)) + i) % 3;
    return {
      ...q,
      options: [...q.options.slice(shift), ...q.options.slice(0, shift)],
      correct: (3 - shift) % 3,
    };
  });
}
