export type Exercise = Question & {
  board: string[];
  hero: string[];
  villain: string[];
  players: number;
  position: string;
  stack: number;
  pot: number;
  blinds: string;
  context: string;
  actions?: boolean;
  opponentStack?: number;
};
const base = {
  board: ["Ac", "8d", "3s"],
  hero: ["Ah", "Qh"],
  villain: [],
  players: 6,
  position: "BTN",
  stack: 50,
  pot: 600,
  blinds: "100 / 200 · анте 0",
};
function q(
  id: string,
  prompt: string,
  options: string[],
  correct: number,
  explanation: string,
  extra: Partial<Exercise> = {},
): Exercise {
  return {
    ...base,
    id,
    prompt,
    options,
    correct,
    explanation,
    topic: "",
    context: "Дополнительное упражнение. Все фишки учебные.",
    ...extra,
  };
}
const percent = (v: number) =>
  (v * 100).toLocaleString("ru-RU", { maximumFractionDigits: 1 }) + "%";
export function exerciseFor(
  category: string,
  index: number,
  players = 6,
): Exercise {
  const n = index % 3;
  let e: Exercise;
  if (category === "guided") {
    const steps = [
      q(
        "",
        "BTN, 50 BB, A♥ Q♥. До вас пас. Учебный план: открыть до 2,5 BB. Какое действие?",
        ["Fold", "Check", "Call", "Bet", "Raise до 500", "All-in"],
        4,
        "Открытие — это рейз относительно BB 200. Игроки SB и BB ещё могут действовать. В учебном продолжении SB пасует, BB коллирует 300.",
        {
          board: [],
          pot: 300,
          actions: true,
          context:
            "Шаг 1. Блайнды 100/200, без анте. Стеки BTN и BB по 10 000; остальные игроки сбрасывают. Учебная линия — один из вариантов.",
        },
      ),
      q(
        "",
        "BB чекнул. A♣ 8♦ 3♠, у вас A♥ Q♥. План: небольшая ставка на вэлью. Выберите действие.",
        ["Fold", "Check", "Call", "Bet 350", "Raise", "All-in"],
        3,
        "Первая ставка на улице — bet. Слабые Ax и некоторые пары могут заплатить. Чек тоже возможен при других допущениях. Здесь BB коллирует 350.",
        {
          pot: 1100,
          stack: 47.5,
          actions: true,
          context:
            "Шаг 2. Префлоп: BTN рейз 500, SB пас, BB колл. Банк 500 + 500 + 100 = 1100. Ставки текущей улицы отсутствуют.",
        },
      ),
      q(
        "",
        "Тёрн 2♣. BB чекнул. План занятия: оставить слабые руки в диапазоне соперника и сыграть без ставки.",
        ["Fold", "Check", "Call", "Bet", "Raise", "All-in"],
        1,
        "Чек сохраняет банк 1800 и не требует фишек. Это учебная линия, а не утверждение, что ставка ошибочна. Решение зависит от диапазона BB.",
        {
          board: ["Ac", "8d", "3s", "2c"],
          pot: 1800,
          stack: 45.75,
          actions: true,
          context:
            "Шаг 3. Флоп: BB чек, BTN bet 350, BB call 350. Банк 1100 + 700 = 1800; у BTN осталось 9150.",
        },
      ),
      q(
        "",
        "Ривер Q♠, BB чекнул. Предполагаем, что BB платит с худшими Ax. План — ставка на вэлью 1200.",
        ["Fold", "Check", "Call", "Bet 1200", "Raise", "All-in"],
        3,
        "У нас две пары: тузы и дамы. В заданной модели худшие Ax платят. Более сильные руки в реальном диапазоне нужно учитывать отдельно. В продолжении BB коллирует.",
        {
          board: ["Ac", "8d", "3s", "2c", "Qs"],
          pot: 1800,
          stack: 45.75,
          actions: true,
          context:
            "Шаг 4. Тёрн: чек–чек. Банк остался 1800. Ставка 1200 составляет 2/3 банка.",
        },
      ),
      q(
        "",
        "BB показал A♦ J♣. Сравните лучшие пятёрки. Кто выигрывает?",
        ["Вы: две пары", "BB: пара тузов", "Раздел банка"],
        0,
        "Ваша пятёрка: A♥ A♣ Q♥ Q♠ 8♦. У BB: A♦ A♣ Q♠ J♣ 8♦. Две пары старше одной. Выигрыш показывает исход, но не доказывает универсальную оптимальность линии.",
        {
          board: ["Ac", "8d", "3s", "2c", "Qs"],
          villain: ["Ad", "Jc"],
          pot: 4200,
          stack: 39.75,
          context:
            "Шаг 5. Ривер: BTN bet 1200, BB call. Банк 1800 + 2400 = 4200. Все фишки виртуальные.",
        },
      ),
    ];
    e = steps[index % steps.length];
  } else if (category === "hands") {
    const deals = [
      {
        board: ["As", "Kd", "7c", "7h", "2s"],
        hero: ["Ah", "Qc"],
        villain: ["Kc", "Kh"],
      },
      {
        board: ["As", "Ks", "Qs", "Js", "Ts"],
        hero: ["2h", "3d"],
        villain: ["9c", "9d"],
      },
      {
        board: ["Ac", "7d", "7h", "4s", "2c"],
        hero: ["Ah", "Kc"],
        villain: ["Ad", "Qc"],
      },
    ];
    const d = deals[n],
      r = showdown(d.board, d.hero, d.villain);
    e = q(
      "",
      "Кому принадлежит лучшая пятёрка?",
      ["Ваша рука", "Рука соперника", "Раздел банка"],
      r.winner > 0 ? 0 : r.winner < 0 ? 1 : 2,
      `У вас: ${r.a.name}. У соперника: ${r.b.name}. ${r.winner === 0 ? "Лучшие пятёрки равны; банк делится." : n === 2 ? "Пары равны, но король-кикер старше дамы." : "Фулл-хаус старше двух пар."}`,
      {
        ...d,
        context:
          "Ривер. Сравните лучшие пять из семи карт. Размер банка не влияет на старшинство.",
      },
    );
  } else if (category === "order") {
    const street = n === 0 ? "preflop" : "postflop",
      folded = n === 2 ? ["SB"] : [],
      p = positions(players),
      answer = actionOrder(players, street, folded)[0];
    e = q(
      "",
      `Кто действует первым ${street === "preflop" ? "на префлопе" : "после флопа"}${folded.length ? ", если SB сбросил" : ""}?`,
      p,
      p.indexOf(answer),
      street === "preflop"
        ? "Первый активный игрок слева от BB."
        : "Первый активный игрок слева от баттона. Сбросившие пропускаются.",
      {
        players,
        board: street === "preflop" ? [] : base.board,
        context:
          "Баттон обозначен D. За столом от 3 до 6 игроков. Для нового размера стола выберите число мест.",
      },
    );
  } else if (category === "raises") {
    e =
      n === 0
        ? q(
            "",
            "BB 200. Открытие до 500. Минимальный полный рейз?",
            ["До 700", `До ${minRaise(500, 300)}`, "До 1000"],
            1,
            "Последний полный шаг = 500 − 200 = 300. Минимум = 500 + 300 = 800.",
            { board: [], pot: 800 },
          )
        : n === 1
          ? q(
              "",
              "Вы открыли до 600 при BB 200. Следом олл-ин до 750, остальные пас. Можно ли вам снова повысить?",
              ["Да, до 900", "Нет: только колл или пас", "Да, любой олл-ин"],
              1,
              "Полный шаг был 400. Короткий олл-ин добавил лишь 150 и не открыл торговлю заново для уже действовавшего игрока.",
              { board: [], pot: 1450 },
            )
          : q(
              "",
              "Вы поставили 100. Олл-ины до 125 и до 200. Ход вернулся к вам. Открыта ли торговля?",
              [
                "Да, совокупное повышение равно 100",
                "Нет, ни один рейз не был полным",
                "Только с разрешения оппонента",
              ],
              0,
              "Суммарно вы столкнулись с полным повышением на 100. Можно повысить минимум до 300. Для коллировавшего 125 игрока ситуация может отличаться.",
              { board: [], pot: 525 },
            );
  } else if (category === "preflop") {
    e =
      n === 0
        ? q(
            "",
            "Все до вас сбросили. BTN, 50 BB, A♠ J♠. Выберите базовую учебную линию.",
            ["Fold", "Check", "Call", "Bet", "Raise до 2,5 BB", "All-in"],
            4,
            "Поздняя позиция и сильная одномастная рука подходят для открытия. 2,5 BB — учебный размер для этих условий, не универсальная стратегия.",
            { board: [], hero: ["As", "Js"], actions: true, pot: 300 },
          )
        : n === 1
          ? q(
              "",
              "UTG, 50 BB, 7♣ 2♦. До вас нет входов в банк.",
              ["Fold", "Check", "Call", "Bet", "Raise", "All-in"],
              0,
              "Ранняя позиция и слабая несвязанная разномастная рука: в заданном учебном сценарии выбираем пас.",
              {
                board: [],
                hero: ["7c", "2d"],
                position: "UTG",
                actions: true,
                pot: 300,
              },
            )
          : q(
              "",
              "BB, BTN открыл 2,2 BB. Сколько нужно добавить для колла?",
              ["1,2 BB", "2,2 BB", "3,2 BB"],
              0,
              "Один BB уже в банке. Доплата = 2,2 − 1 = 1,2 BB. Само решение о колле зависит от руки и диапазона.",
              { board: [], hero: ["Kh", "Qh"], position: "BB", pot: 740 },
            );
  } else if (category === "math") {
    const cycle = index % 6;
    e =
      cycle === 0
        ? q(
            "",
            "Банк 1000 до ставки, соперник поставил 500. Какой порог equity у колла?",
            ["20%", percent(potOdds(1000, 500)), "33,3%"],
            1,
            "Equity = колл / итоговый банк = 500 / (1000 + 500 + 500) = 25%. Будущих ставок нет.",
            { pot: 1500 },
          )
        : cycle === 1
          ? q(
              "",
              "Equity 30%, P=1000, ставка и колл по 500. EV колла без будущих ставок?",
              [
                `${callEV(1000, 500, 0.3) > 0 ? "+" : ""}${callEV(1000, 500, 0.3)}`,
                "−200",
                "+600",
              ],
              0,
              "EV(call) = 0,30 × 2000 − 500 = +100 учебных фишек.",
              { pot: 1500 },
            )
          : cycle === 2
            ? q(
                "",
                "9 чистых аутов на флопе. Вероятность улучшения к риверу без дальнейших затрат?",
                ["Около 35%", "Ровно 18%", "Ровно 50%"],
                0,
                "1 − (38/47 × 37/46) ≈ 34,97%. Это вероятность увидеть обе карты; платить за тёрн отдельно в модели нельзя.",
                { hero: ["Ah", "Qh"], board: ["Kh", "8h", "3s"] },
              )
            : cycle === 3
              ? q(
                  "",
                  "Чистый блеф 750 в банк 1000. Порог фолда?",
                  [percent(bluffThreshold(1000, 750)), "25%", "75%"],
                  0,
                  "750 / (1000 + 750) ≈ 42,9%. При колле блеф всегда проигрывает.",
                  { pot: 1000 },
                )
              : cycle === 4
                ? q(
                    "",
                    "Ставка 500 в банк 1000. MDF в упрощённой модели?",
                    [percent(mdf(1000, 500)), "50%", "33,3%"],
                    0,
                    "1000 / (1000 + 500) ≈ 66,7%. Ориентир диапазона, а не обязательный колл каждой руки.",
                    { pot: 1500 },
                  )
                : q(
                    "",
                    "На тёрне 9 чистых аутов. Вероятность попасть на ривере?",
                    ["Около 19,6%", "Около 35%", "Ровно 18%"],
                    0,
                    "9 / 46 ≈ 19,57%. Известны 2 личные и 4 общие карты.",
                    { board: ["Kh", "8h", "3s", "2c"] },
                  );
  } else if (category === "postflop") {
    e =
      n === 0
        ? q(
            "",
            "Вы BTN с A♥ Q♥. BB чекнул на A♣ 8♦ 3♠. Для учебной линии со ставкой выберите цель.",
            [
              "Вэлью: получить колл от худших",
              "Блеф: выбить лучшую руку",
              "Ставка без цели",
            ],
            0,
            "Топ-пара с сильным кикером может получить оплату от худших Ax и пар. Возможен и чек: частота зависит от диапазонов.",
            { pot: 1100 },
          )
        : n === 1
          ? q(
              "",
              "Все до вас чекнули. У вас 9♠ 8♠ на 7♦ 6♣ 2♥. Учебное задание: реализовать equity без увеличения банка.",
              ["Fold", "Check", "Call", "Bet", "Raise", "All-in"],
              1,
              "Чек доступен при отсутствии ставки и сохраняет возможность улучшиться. Ставка как полублеф тоже бывает обоснована, но решает другую задачу.",
              { hero: ["9s", "8s"], board: ["7d", "6c", "2h"], actions: true },
            )
          : q(
              "",
              "У вас натс на ривере. Соперник поставил последние 500, у вас тоже осталось 500. Учебная цель: получить доступ к банку.",
              [
                "Fold",
                "Check",
                "Call / All-in 500",
                "Bet",
                "Raise",
                "All-in 1000",
              ],
              2,
              "Колл всех оставшихся 500 является олл-ином. Повысить при таком остатке нельзя. Сильнейшая рука не может проиграть, но иногда делит банк.",
              {
                hero: ["As", "Ks"],
                board: ["Qs", "Js", "Ts", "2c", "3d"],
                stack: 2.5,
                pot: 2000,
                actions: true,
              },
            );
  } else if (category === "tournament") {
    e =
      n === 0
        ? q(
            "",
            "30 000 фишек, большой блайнд вырос до 3000. Ваш стек?",
            [`${stackBB(30000, 3000)} BB`, "30 BB", "100 BB"],
            0,
            "30 000 / 3000 = 10 BB. Число фишек прежнее, но глубина изменилась.",
            { stack: 10, board: [], blinds: "1500 / 3000 · анте 0" },
          )
        : n === 1
          ? q(
              "",
              "У вас 40 BB, у оппонента 15 BB. Эффективный стек между вами?",
              ["15 BB", "40 BB", "55 BB"],
              0,
              "Меньший стек ограничивает взаимный риск. Против третьего игрока может быть другой эффективный стек.",
              { stack: 40, opponentStack: 15, board: [] },
            )
          : q(
              "",
              "При 12 BB можно ли выбрать универсальный диапазон колла олл-ина без позиции и наград?",
              [
                "Нет, вводных недостаточно",
                "Да, любые две картинки",
                "Да, любой туз",
              ],
              0,
              "Нужны позиции, диапазон пуша, анте и структура очков/наград. Если ICM не соответствует формату, используйте регламент начисления очков.",
              { stack: 12, board: [] },
            );
  } else {
    e =
      n === 0
        ? q(
            "",
            "Инициатор олл-ина запросил первый двойной прогон на тёрне. Что открываем дважды?",
            ["Только ривер", "Весь борд", "Тёрн и ривер"],
            0,
            twoBoards("turn", 0, true) + " Согласие соперника не требуется.",
            { board: ["Ac", "8d", "3s", "5h"] },
          )
        : n === 1
          ? q(
              "",
              "Игрок уже дважды использовал опцию. Может ли инициировать третий запрос?",
              ["Нет", "Да, без ограничений", "Да, если попросит зритель"],
              0,
              twoBoards("flop", 2, true),
            )
          : q(
              "",
              "Мультивей, нечётные фишки, несколько запросов: как поступить?",
              [
                "Уточнить регламент клуба",
                "Придумать единое правило",
                "Всегда отдать остаток BTN",
              ],
              0,
              "Эти случаи не определены исходными условиями. До раздачи уточните письменный регламент клуба.",
            );
  }
  const topic = categories.find((c) => c.id === category)?.name ?? "Практика";
  // У вариантов тоже меняется порядок; у действий сохраняется привычная последовательность.
  if (!e.actions) {
    const shift = index % e.options.length;
    e = {
      ...e,
      options: [...e.options.slice(shift), ...e.options.slice(0, shift)],
      correct: (e.correct - shift + e.options.length) % e.options.length,
    };
  }
  return {
    ...e,
    id: `${category}-${index}${category === "order" ? `-${players}` : ""}`,
    topic,
  };
}
